#!/usr/bin/env python3
# The Android host's source list, taken from dm/host/Makefile instead of copied by hand (the same idea as iOS's ios/tools/gen_build.py):
# SRC and GFX are read as make would read them (plain names and $(sort $(wildcard ...)) expanded against dm/host), then the files the
# Android build does not take are dropped: *.m (Objective-C; Android has its own front end and no Metal), *.S (Mach-O assembly; the
# three the host needs go through tools/asm_elf.py in CMakeLists.txt), front_*.m, and main.c (built on its own: the command-line
# dmhost keeps the name main, the App's libdm.so builds it with -Dmain=dm_main).
# Writes a CMake fragment with HOST_SRCS and GFX_SRCS (absolute paths) and the Makefile's VPX directory. Exits 1 with a [RED] line
# when a variable is missing, so a renamed Makefile variable stops the configure instead of building an empty host.
# Usage: host_sources.py <dm/host/Makefile> <out.cmake>
import glob
import os
import re
import sys


def variable(text, name):
    # the value of NAME=... (one logical line; a trailing comment dropped)
    m = re.search(r'^%s\s*[:?]?=\s*(.*)$' % re.escape(name), text, re.M)
    if not m:
        raise SystemExit('[RED] host_sources: dm/host/Makefile has no %s= line' % name)
    return m.group(1).split('#', 1)[0].strip()


def expand(value, host):
    # plain names and $(sort $(wildcard a b ...)) items, resolved against dm/host; other $(...) forms are an error, not a guess
    out = []
    for token in re.findall(r'\$\(sort \$\(wildcard ([^()]*)\)\)|\$\(wildcard ([^()]*)\)|(\$\([^()]*\))|(\S+)', value):
        patterns = token[0] or token[1]
        if patterns:
            for pattern in patterns.split():
                out += sorted(glob.glob(os.path.join(host, pattern)))
        elif token[2]:
            raise SystemExit('[RED] host_sources: unsupported make expression %s' % token[2])
        else:
            out.append(os.path.join(host, token[3]))
    return [os.path.normpath(p) for p in out]


def android_takes(path):
    name = os.path.basename(path)
    if name.endswith(('.m', '.S')) or name == 'main.c' or name.startswith('front_'):
        return False
    return True


def main():
    if len(sys.argv) != 3:
        raise SystemExit('usage: host_sources.py <dm/host/Makefile> <out.cmake>')
    makefile, out = sys.argv[1], sys.argv[2]
    host = os.path.dirname(os.path.abspath(makefile))
    text = open(makefile, encoding='utf-8').read().replace('\\\n', ' ')
    host_srcs = [p for p in expand(variable(text, 'SRC'), host) if android_takes(p)]
    gfx_srcs = [p for p in expand(variable(text, 'GFX'), host) if android_takes(p)]
    vpx = os.path.normpath(os.path.join(host, variable(text, 'VPX')))
    missing = [p for p in host_srcs + gfx_srcs if not os.path.isfile(p)]
    if missing:
        raise SystemExit('[RED] host_sources: dm/host/Makefile names files that do not exist: %s' % ' '.join(missing))

    def cmake_list(name, items):
        return 'set(%s\n%s)\n' % (name, ''.join('  "%s"\n' % p.replace('\\', '/') for p in items))

    body = ('# Generated by dm/android/tools/host_sources.py from dm/host/Makefile; do not edit\n'
            + cmake_list('HOST_SRCS', host_srcs) + cmake_list('GFX_SRCS', gfx_srcs)
            + 'set(VPX_DIR "%s")\n' % vpx.replace('\\', '/'))
    os.makedirs(os.path.dirname(os.path.abspath(out)), exist_ok=True)
    if not os.path.exists(out) or open(out, encoding='utf-8').read() != body:
        open(out, 'w', encoding='utf-8', newline='\n').write(body)
    return 0


if __name__ == '__main__':
    sys.exit(main())
